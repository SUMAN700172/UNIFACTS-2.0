function setupAudio() {
    if (state.audio.context) return;
    
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    state.audio.context = new AudioContext();
    
    // 1. Create a deep space ambient drone hum
    const osc1 = state.audio.context.createOscillator();
    const osc2 = state.audio.context.createOscillator();
    const lfo = state.audio.context.createOscillator();
    
    const lfoGain = state.audio.context.createGain();
    const filter = state.audio.context.createBiquadFilter();
    state.audio.gainNode = state.audio.context.createGain();
    
    // Set oscillator frequencies for dark bass chord (C1 & G1)
    osc1.type = 'sine';
    osc1.frequency.setValueAtTime(65.41, state.audio.context.currentTime); // C2
    osc2.type = 'triangle';
    osc2.frequency.setValueAtTime(98.00, state.audio.context.currentTime); // G2
    
    // LFO to slowly sweep filter frequency (creating a breathing wind/drone)
    lfo.frequency.setValueAtTime(0.08, state.audio.context.currentTime); // very slow
    lfoGain.gain.setValueAtTime(120, state.audio.context.currentTime);
    
    filter.type = 'lowpass';
    filter.Q.setValueAtTime(3.5, state.audio.context.currentTime);
    filter.frequency.setValueAtTime(220, state.audio.context.currentTime);
    
    // Connect nodes
    lfo.connect(lfoGain);
    lfoGain.connect(filter.frequency);
    
    osc1.connect(filter);
    osc2.connect(filter);
    
    // Dynamic soft volume
    state.audio.gainNode.gain.setValueAtTime(0.0, state.audio.context.currentTime); // Start silent
    filter.connect(state.audio.gainNode);
    state.audio.gainNode.connect(state.audio.context.destination);
    
    // Start oscillators
    osc1.start();
    osc2.start();
    lfo.start();
    
    state.audio.ambientNode = { osc1, osc2, lfo, filter };
}

function toggleSoundscape() {
    const btn = document.getElementById('audio-toggle');
    if (!btn) return;
    const label = btn.querySelector('span');
    const icon = btn.querySelector('i');
    
    setupAudio();
    
    if (state.audio.context.state === 'suspended') {
        state.audio.context.resume();
    }
    
    if (state.audio.isPlaying) {
        // Fade out
        state.audio.gainNode.gain.linearRampToValueAtTime(0.0, state.audio.context.currentTime + 1.2);
        icon.className = 'fa-solid fa-volume-xmark';
        label.innerText = 'Soundscape: Off';
        state.audio.isPlaying = false;
        
        // Stop alignment sound if active
        if (state.audio.humNode) {
            state.audio.humNode.gainNode.gain.setTargetAtTime(0, state.audio.context.currentTime, 0.1);
        }
    } else {
        // Fade in
        state.audio.gainNode.gain.linearRampToValueAtTime(0.2, state.audio.context.currentTime + 1.5);
        icon.className = 'fa-solid fa-volume-high';
        label.innerText = 'Soundscape: On';
        state.audio.isPlaying = true;
        
        // Connect alignment hum if we are in decoder section
        startDecoderHum();
        playSynthBeep(440, 'triangle', 0.15, 0.05);
    }
}

// Play modular synthesizer sounds for UI events
function playSynthBeep(freq, type, duration, volume) {
    if (!state.audio.context || !state.audio.isPlaying) return;
    
    const osc = state.audio.context.createOscillator();
    const gain = state.audio.context.createGain();
    
    osc.type = type || 'sine';
    osc.frequency.setValueAtTime(freq, state.audio.context.currentTime);
    
    gain.gain.setValueAtTime(volume || 0.1, state.audio.context.currentTime);
    // Exponential decay
    gain.gain.exponentialRampToValueAtTime(0.0001, state.audio.context.currentTime + duration);
    
    osc.connect(gain);
    gain.connect(state.audio.context.destination);
    
    osc.start();
    osc.stop(state.audio.context.currentTime + duration);
}

