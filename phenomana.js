// Generates dynamic interactive statics synth humming depending on dial status
function playTelescopeStaticHum() {
    if (!state.audio.context || !state.audio.isPlaying) return;
    
    // Initialize continuous hum oscillator
    if (!state.audio.humNode) {
        const osc = state.audio.context.createOscillator();
        const gainNode = state.audio.context.createGain();
        const bpf = state.audio.context.createBiquadFilter();
        
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(120, state.audio.context.currentTime); // Deep pitch hum
        
        bpf.type = 'bandpass';
        bpf.Q.setValueAtTime(5, state.audio.context.currentTime);
        bpf.frequency.setValueAtTime(300, state.audio.context.currentTime);
        
        gainNode.gain.setValueAtTime(0.015, state.audio.context.currentTime);
        
        osc.connect(bpf);
        bpf.connect(gainNode);
        gainNode.connect(state.audio.context.destination);
        osc.start();
        
        state.audio.humNode = { osc, gainNode, bpf };
    }
    
    // Update hum pitch & volume based on dial frequencies and alignment success
    const alignment = computeAlignmentRatio();
    const frequencyFactor = state.decoder.current.freq;
    
    // As player matches signal, hum becomes clean and high-pitched harmonic chord
    const baseFreq = 80 + frequencyFactor * 1.5;
    const filterFreq = 200 + alignment * 800;
    
    state.audio.humNode.osc.frequency.setTargetAtTime(baseFreq, state.audio.context.currentTime, 0.05);
    state.audio.humNode.bpf.frequency.setTargetAtTime(filterFreq, state.audio.context.currentTime, 0.05);
    state.audio.humNode.gainNode.gain.setTargetAtTime(0.01 + (alignment * 0.02), state.audio.context.currentTime, 0.05);
}

function startDecoderHum() {
    if (state.audio.isPlaying) {
        playTelescopeStaticHum();
    }
}

// Compute mathematically how close current dials match the astronomical target signal
function computeAlignmentRatio() {
    const cur = state.decoder.current;
    const tar = state.decoder.target;
    
    // Standard differences normalized
    const diffFreq = Math.abs(cur.freq - tar.freq) / 90;
    const diffFilter = Math.abs(cur.filter - tar.filter) / 45;
    const diffPhase = Math.abs(cur.phase - tar.phase) / 360;
    const diffGain = Math.abs(cur.gain - tar.gain) / 90;
    
    const avgDiff = (diffFreq + diffFilter + diffPhase + diffGain) / 4;
    return Math.max(0, 1 - avgDiff); // 0.0 to 1.0
}

function checkSignalAlignment() {
    const alignment = computeAlignmentRatio();
    const percent = Math.floor(alignment * 100);
    
    const alignSpan = document.getElementById('match-percentage');
    alignSpan.innerText = `Alignment: ${percent}%`;
    
    const decodeBtn = document.getElementById('decode-btn');
    
    if (percent >= 94) {
        state.decoder.isAligned = true;
        alignSpan.classList.add('text-green');
        alignSpan.classList.remove('text-cyan');
        decodeBtn.disabled = false;
        
        // Pulse glow decoder button
        decodeBtn.classList.add('glow-active');
    } else {
        state.decoder.isAligned = false;
        alignSpan.classList.remove('text-green');
        alignSpan.classList.add('text-cyan');
        decodeBtn.disabled = true;
        decodeBtn.classList.remove('glow-active');
    }
}

// Waveforms visual renderer
function runDecoderOscilloscopeLoop() {
    const canvas = state.decoder.canvas;
    const ctx = state.decoder.ctx;
    
    if (!canvas || !ctx) return;
    
    // Clear canvas
    ctx.fillStyle = '#03060f';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    const time = Date.now() * 0.003;
    const centerY = canvas.height / 2;
    
    // 1. Draw Target astronomical signal (Cyan line)
    ctx.strokeStyle = 'rgba(6, 182, 212, 0.75)';
    ctx.lineWidth = 2;
    ctx.beginPath();
    
    const tFreq = state.decoder.target.freq * 0.0015;
    const tAmp = state.decoder.target.gain * 0.8;
    const tFilter = state.decoder.target.filter;
    const tPhase = (state.decoder.target.phase * Math.PI) / 180;
    
    for (let x = 0; x < canvas.width; x++) {
        // Composite mathematical target wave formula (complex harmonic wave)
        const y = centerY + Math.sin(x * tFreq + time * 1.5 + tPhase) * tAmp * Math.cos(x * 0.005);
        if (x === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
    }
    ctx.stroke();
    
    // 2. Draw Incoming scrambled signal (Magenta line)
    ctx.strokeStyle = 'rgba(236, 72, 153, 0.7)';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    
    const cFreq = state.decoder.current.freq * 0.0015;
    const cAmp = state.decoder.current.gain * 0.8;
    const cFilter = state.decoder.current.filter;
    const cPhase = (state.decoder.current.phase * Math.PI) / 180;
    
    for (let x = 0; x < canvas.width; x++) {
        // Scrambled frequency depends on filter knob (adds noisy sine waves)
        const noise = Math.sin(x * 0.15 + time * 6) * cFilter * 0.6 * (1 - computeAlignmentRatio());
        const y = centerY + Math.sin(x * cFreq + time * 1.5 + cPhase) * cAmp * Math.cos(x * 0.005) + noise;
        
        if (x === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
    }
    ctx.stroke();
    
    state.decoder.animationId = requestAnimationFrame(runDecoderOscilloscopeLoop);
}

