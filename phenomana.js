/* --- Simulator 2: Dark Matter Network Filaments --- */
let dmParticles = [];
function renderDarkMatterNetSimulator(ctx, cx, cy, params) {
    const density = params.density || 20;
    const expansion = (params.expansion || 3) * 0.2;
    const nodesCount = params.nodes || 40;
    const time = state.simulator.time;
    
    // Regenerate nodes array if count changes
    if (dmParticles.length !== nodesCount) {
        dmParticles = [];
        for (let i = 0; i < nodesCount; i++) {
            dmParticles.push({
                x: Math.random() * ctx.canvas.width,
                y: Math.random() * ctx.canvas.height,
                vx: (Math.random() - 0.5) * 1.5,
                vy: (Math.random() - 0.5) * 1.5,
                pulseOffset: Math.random() * Math.PI
            });
        }
    }
    
    // Draw cosmic filaments (lines between nodes)
    ctx.strokeStyle = `rgba(139, 92, 246, ${0.15 + (density * 0.005)})`;
    ctx.lineWidth = 1;
    
    dmParticles.forEach((p, idx) => {
        // Move particles reacting to expansion rate
        p.x += p.vx * (1 + expansion);
        p.y += p.vy * (1 + expansion);
        
        // Bounce from canvas edges
        if (p.x < 15 || p.x > ctx.canvas.width - 15) p.vx *= -1;
        if (p.y < 15 || p.y > ctx.canvas.height - 15) p.vy *= -1;
        
        // Draw filaments connection lines to nearby nodes
        for (let j = idx + 1; j < dmParticles.length; j++) {
            const dest = dmParticles[j];
            const dist = Math.hypot(dest.x - p.x, dest.y - p.y);
            if (dist < 130) {
                ctx.beginPath();
                ctx.moveTo(p.x, p.y);
                ctx.lineTo(dest.x, dest.y);
                ctx.stroke();
            }
        }
        
        // Render node points (glowing galaxy clusters)
        const pulse = 0.5 + Math.sin(time * 2 + p.pulseOffset) * 0.5;
        const radius = 2 + pulse * 4 * (density * 0.04);
        
        const grad = ctx.createRadialGradient(p.x, p.y, 0, p.x, p.y, radius * 3);
        grad.addColorStop(0, 'rgba(0, 242, 254, 0.9)');
        grad.addColorStop(0.3, 'rgba(168, 85, 247, 0.5)');
        grad.addColorStop(1, 'transparent');
        
        ctx.fillStyle = grad;
        ctx.beginPath();
        ctx.arc(p.x, p.y, radius * 3, 0, Math.PI * 2);
        ctx.fill();
        
        ctx.fillStyle = '#ffffff';
        ctx.beginPath();
        ctx.arc(p.x, p.y, 1.5, 0, Math.PI * 2);
        ctx.fill();
    });
    
    // Update active HUD
    const webDisplay = document.getElementById('hud-web');
    if (webDisplay) webDisplay.innerText = `${(density * 1.8 + expansion * 2).toFixed(1)}%`;
}

