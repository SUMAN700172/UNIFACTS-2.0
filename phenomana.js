// Setup Starfield Particle System
function initStarfield() {
    const canvas = document.getElementById('starfield-canvas');
    const ctx = canvas.getContext('2d');
    
    function resizeCanvas() {
        canvas.width = window.innerWidth;
        canvas.height = window.innerHeight;
        generateStars(canvas.width, canvas.height);
    }
    
    window.addEventListener('resize', resizeCanvas);
    resizeCanvas();
    
    // Handle mouse movement to shift depth
    window.addEventListener('mousemove', (e) => {
        state.starfield.mouse.targetX = (e.clientX - window.innerWidth / 2) * 0.05;
        state.starfield.mouse.targetY = (e.clientY - window.innerHeight / 2) * 0.05;
    });
}

function generateStars(w, h) {
    state.starfield.stars = [];
    const count = Math.min(250, Math.floor((w * h) / 6000));
    
    for (let i = 0; i < count; i++) {
        state.starfield.stars.push({
            x: Math.random() * w,
            y: Math.random() * h,
            size: Math.random() * 1.5 + 0.5,
            twinkleSpeed: Math.random() * 0.03 + 0.005,
            twinklePhase: Math.random() * Math.PI,
            depth: Math.random() * 0.8 + 0.2, // Depth factor for parallax
            color: getRandomStellarColor()
        });
    }

    // Generate soft floating cosmic clouds
    state.starfield.nebulae = [];
    for (let i = 0; i < 3; i++) {
        state.starfield.nebulae.push({
            x: Math.random() * w,
            y: Math.random() * h,
            radius: Math.random() * 250 + 150,
            color: i === 0 ? 'rgba(180, 100, 255, 0.08)' : (i === 1 ? 'rgba(0, 242, 254, 0.06)' : 'rgba(219, 39, 119, 0.06)'),
            vx: (Math.random() - 0.5) * 0.15,
            vy: (Math.random() - 0.5) * 0.15
        });
    }
}

function getRandomStellarColor() {
    const colors = [
        '#ffffff', // White
        '#e0f2fe', // Soft Blue
        '#fae8ff', // Soft Pink
        '#bae6fd', // Cyan-Blue
        '#fef08a'  // Light Yellow
    ];
    return colors[Math.floor(Math.random() * colors.length)];
}

function animateStarfield() {
    const canvas = document.getElementById('starfield-canvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    
    // Clear & redraw space background
    ctx.fillStyle = '#040509';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    // Smoothly interpolate mouse parallax shifts
    state.starfield.mouse.x += (state.starfield.mouse.targetX - state.starfield.mouse.x) * 0.05;
    state.starfield.mouse.y += (state.starfield.mouse.targetY - state.starfield.mouse.y) * 0.05;
    
    // 1. Draw Nebulae clouds first (deep space back)
    ctx.globalCompositeOperation = 'screen';
    state.starfield.nebulae.forEach(n => {
        // Drifting motion
        n.x += n.vx;
        n.y += n.vy;
        
        // Bounce bounds
        if (n.x < -n.radius) n.x = canvas.width + n.radius;
        if (n.x > canvas.width + n.radius) n.x = -n.radius;
        if (n.y < -n.radius) n.y = canvas.height + n.radius;
        if (n.y > canvas.height + n.radius) n.y = -n.radius;
        
        const shiftX = n.x + state.starfield.mouse.x * 0.1;
        const shiftY = n.y + state.starfield.mouse.y * 0.1;
        
        const grad = ctx.createRadialGradient(shiftX, shiftY, 0, shiftX, shiftY, n.radius);
        grad.addColorStop(0, n.color);
        grad.addColorStop(1, 'transparent');
        ctx.fillStyle = grad;
        ctx.beginPath();
        ctx.arc(shiftX, shiftY, n.radius, 0, Math.PI * 2);
        ctx.fill();
    });
    ctx.globalCompositeOperation = 'source-over';
    
    // 2. Draw stars with twinkling phase and depth parallax
    state.starfield.stars.forEach(s => {
        s.twinklePhase += s.twinkleSpeed;
        const alpha = 0.3 + Math.abs(Math.sin(s.twinklePhase)) * 0.7;
        
        // Apply parallax offset based on star depth and mouse position
        const posX = s.x + state.starfield.mouse.x * s.depth;
        const posY = s.y + state.starfield.mouse.y * s.depth;
        
        // Wrap stars around viewport bounds
        let finalX = posX % canvas.width;
        let finalY = posY % canvas.height;
        if (finalX < 0) finalX += canvas.width;
        if (finalY < 0) finalY += canvas.height;
        
        ctx.fillStyle = s.color;
        ctx.globalAlpha = alpha;
        ctx.beginPath();
        ctx.arc(finalX, finalY, s.size, 0, Math.PI * 2);
        ctx.fill();
    });
    ctx.globalAlpha = 1.0;
    
    requestAnimationFrame(animateStarfield);
}

